"""Run the NyayaMate AI pipeline on every test case and save UNEDITED outputs.

Usage:
    python run_tests.py                     # real AI via OpenRouter (needs OPENROUTER_API_KEY)
    python run_tests.py --model google/gemma-3-27b-it:free
    python run_tests.py --only tc02_unpaid_salary
    python run_tests.py --demo              # offline rule-based engine -> outputs_demo/ (not AI)

Saves:
    outputs/raw/<test_id>/NN_<task>_attemptK.txt   raw model text, byte-for-byte as received
    outputs/raw/<test_id>/run_meta.json            model, timestamps, errors
    outputs/structured/<test_id>.json              validated outputs + citation warnings
    outputs/documents/<test_id>_<doc>.txt          generated document draft
Then run:  python evaluate.py
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from datetime import datetime
from pathlib import Path

from core import legal_ai
from core.ai_client import AIServiceError, OpenRouterClient
from core.config import BASE_DIR, DEFAULT_MODEL, TEST_CASES_DIR, get_env_api_key


def save_text(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def compose_document(d: dict) -> str:
    return ("DRAFT – generated by NyayaMate AI. Not legal advice. Review before sending.\n"
            + "=" * 70 + "\n\n"
            f"{d['sender_name']}\n{d['sender_address']}\n\n{d['date']}\n\nTo,\n"
            f"{d['recipient_name']}\n{d['recipient_address']}\n\nSubject: {d['subject']}\n\n"
            f"{d['body']}\n\n--\nSupporting documents:\n"
            + "\n".join(f"- {x}" for x in d["supporting_documents"])
            + "\n\nPlaceholders to fill:\n" + "\n".join(f"- {x}" for x in d["placeholders_to_fill"]))


def run_case(tc: dict, client, demo: bool, out_root: Path, delay: float) -> dict:
    tid = tc["id"]
    raw_dir = out_root / "raw" / tid
    raw_dir.mkdir(parents=True, exist_ok=True)
    for old in raw_dir.glob("*.txt"):
        old.unlink()
    record = {"test_id": tid, "title": tc["title"], "user_input": tc["user_input"],
              "run_started": datetime.now().isoformat(timespec="seconds"),
              "mode": "demo (rule-based, NOT AI)" if demo else "ai", "steps": {}, "errors": []}
    step_no = 0

    def step(name, fn, *args, **kwargs):
        nonlocal step_no
        step_no += 1
        print(f"  [{tid}] {name} …", flush=True)
        try:
            res = fn(client, *args, demo=demo, **kwargs)
        except AIServiceError as e:
            for k, r in enumerate(getattr(e, "raw_outputs", []) or [], 1):
                save_text(raw_dir / f"{step_no:02d}_{name}_attempt{k}_INVALID.txt", r)
            record["errors"].append({"step": name, "kind": e.kind, "message": e.message,
                                     "detail": e.detail[:1000]})
            print(f"    ✗ {e.kind}: {e.message}", flush=True)
            return None
        for k, r in enumerate(res.raw_outputs, 1):
            save_text(raw_dir / f"{step_no:02d}_{name}_attempt{k}.txt", r)
        record["steps"][name] = res.to_dict()
        print(f"    ✓ model={res.model} warnings={len(res.citation_warnings)}", flush=True)
        if delay and not demo:
            time.sleep(delay)
        return res

    history = [{"role": "user", "content": tc["user_input"]}]
    step("chat_reply", legal_ai.chat_reply, history, "Auto-detect")
    cls = step("classify", legal_ai.classify_legal_issue, tc["user_input"])
    fx = step("extract_facts", legal_ai.extract_case_facts, tc["user_input"])
    if cls and fx:
        area = cls.data["issue_area"]
        lang = cls.data.get("language") or "English"
        step("guidance", legal_ai.generate_legal_guidance, fx.data, area, lang)
        doc_key = tc.get("expected", {}).get("doc_type") or \
            legal_ai.suggest_document_type(area, fx.data)
        doc = step("document", legal_ai.generate_legal_document, fx.data, doc_key, area,
                   "English")
        if doc:
            save_text(out_root / "documents" / f"{tid}_{doc_key}.txt", compose_document(doc.data))
            record["document_type"] = doc_key
        step("checklist", legal_ai.generate_evidence_checklist, fx.data)

    record["run_finished"] = datetime.now().isoformat(timespec="seconds")
    save_text(raw_dir / "run_meta.json", json.dumps(
        {k: record[k] for k in ("test_id", "mode", "run_started", "run_finished", "errors")} |
        {"models": {k: v["model"] for k, v in record["steps"].items()}},
        ensure_ascii=False, indent=2))
    save_text(out_root / "structured" / f"{tid}.json",
              json.dumps(record, ensure_ascii=False, indent=2))
    return record


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--model", default=DEFAULT_MODEL)
    ap.add_argument("--only", help="run a single test id")
    ap.add_argument("--demo", action="store_true", help="offline rule-based engine (NOT AI)")
    ap.add_argument("--delay", type=float, default=3.0,
                    help="seconds between AI calls (helps with free-model rate limits)")
    args = ap.parse_args()

    out_root = BASE_DIR / ("outputs_demo" if args.demo else "outputs")
    client = None
    if not args.demo:
        try:
            client = OpenRouterClient(get_env_api_key(), args.model)
        except AIServiceError as e:
            sys.exit(f"Cannot run AI tests: {e.message}\n(Use --demo for the offline engine.)")

    cases = sorted(TEST_CASES_DIR.glob("*.json"))
    if args.only:
        cases = [p for p in cases if p.stem == args.only]
    if not cases:
        sys.exit("No test cases found.")
    print(f"Running {len(cases)} test case(s) – mode={'DEMO' if args.demo else 'AI'} "
          f"model={args.model if not args.demo else 'n/a'}")
    summary = []
    for p in cases:
        tc = json.loads(p.read_text(encoding="utf-8"))
        rec = run_case(tc, client, args.demo, out_root, args.delay)
        summary.append((tc["id"], len(rec["steps"]), len(rec["errors"])))
    print("\nDone.")
    for tid, ok, err in summary:
        print(f"  {tid}: {ok} steps OK, {err} error(s)")
    print(f"\nOutputs in {out_root}. Next: python evaluate.py"
          + (" --demo" if args.demo else ""))


if __name__ == "__main__":
    main()
